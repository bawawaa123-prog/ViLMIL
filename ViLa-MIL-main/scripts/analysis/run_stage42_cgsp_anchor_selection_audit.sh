NUM_EXAMPLES="${NUM_EXAMPLES:-30}"
SEED="${SEED:-1}"

CMD=(
    "${PYTHON_BIN}" "scripts/analysis/build_stage42_cgsp_anchor_selection_audit.py"
    "--data_root_dir" "${DATA_ROOT_DIR}"
    "--data_folder_s" "${DATA_FOLDER_S}"
    "--data_folder_l" "${DATA_FOLDER_L}"
    "--csv_path" "${CSV_PATH}"
    "--split_dir" "${SPLIT_DIR}"
    "--fold" "${FOLD}"
    "--split" "${SPLIT}"
    "--output_dir" "${OUTPUT_DIR}"
    "--stage41_manifest" "${STAGE41_MANIFEST}"
    "--concept_prompt_path" "${CONCEPT_PROMPT_PATH}"
    "--checkpoint_path" "${CHECKPOINT_PATH}"
    "--max_slides" "${MAX_SLIDES}"
    "--low_patch_size" "${LOW_PATCH_SIZE}"
    "--high_patch_size" "${HIGH_PATCH_SIZE}"
    "--bbox_expand_values" "${BBOX_EXPAND_VALUES}"
    "--proposal_radius" "${PROPOSAL_RADIUS}"
    "--nms_radius" "${NMS_RADIUS}"
    "--num_anchors" "${NUM_ANCHORS}"
    "--candidate_top_l" "${CANDIDATE_TOP_L}"
    "--top_g_concepts" "${TOP_G_CONCEPTS}"
    "--per_concept_top_m" "${PER_CONCEPT_TOP_M}"
    "--prompt_topk" "${PROMPT_TOPK}"
    "--margin_weight" "${MARGIN_WEIGHT}"
    "--high_child_top_m" "${HIGH_CHILD_TOP_M}"
    "--num_examples" "${NUM_EXAMPLES}"
    "--seed" "${SEED}"
)

