#!/usr/bin/env bash

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "${ROOT_DIR}"

PYTHON_BIN="${PYTHON_BIN:-/home/ljh/anaconda3/envs/vila_mil/bin/python}"
DATA_ROOT_DIR="${DATA_ROOT_DIR:-/xiangmu/data/VILMIL}"
DATA_FOLDER_S="${DATA_FOLDER_S:-features_biomedclip_5x}"
DATA_FOLDER_L="${DATA_FOLDER_L:-features_biomedclip_20x}"
CSV_PATH="${CSV_PATH:-${ROOT_DIR}/dataset_csv/all_data.csv}"
SPLIT_DIR="${SPLIT_DIR:-${ROOT_DIR}/splits/adenocarcinoma/task_adenocarcinoma_strictcv_100}"
FOLD="${FOLD:-0}"
SPLIT="${SPLIT:-test}"
OUTPUT_DIR="${OUTPUT_DIR:-${ROOT_DIR}/results_stage42/cgsp_anchor_selection_audit}"
STAGE41_MANIFEST="${STAGE41_MANIFEST:-${ROOT_DIR}/results_stage41/low_high_coordinate_audit/stage41_manifest.json}"
CONCEPT_PROMPT_PATH="${CONCEPT_PROMPT_PATH:-${ROOT_DIR}/dataset_csv/private_lung_concept_prompt_pool_stage2_core12.json}"
